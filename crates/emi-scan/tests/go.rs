//! Go scope assembly on a small module.

use std::path::PathBuf;

use emi_scan::{Options, Probe, scan};

struct Tree(PathBuf);

impl Drop for Tree {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

#[test]
fn module_packages_tests_generated_and_ignored() {
    let root = Tree(std::env::temp_dir().join(format!("emi-go-scan-{}", std::process::id())));
    let _ = std::fs::remove_dir_all(&root.0);
    let files = [
        ("go.mod", "module example.com/app\n\ngo 1.22\n"),
        (
            "main.go",
            "package main\n\nimport \"example.com/app/db\"\n\nfunc main() { db.Open() }\n",
        ),
        ("db/db.go", "package db\n\nfunc Open() {}\n"),
        (
            "db/db_test.go",
            "package db\n\nimport \"testing\"\n\nfunc TestOpen(t *testing.T) { Open() }\n",
        ),
        (
            "db/zz_gen.go",
            "// Code generated by gen; DO NOT EDIT.\n\npackage db\n\nvar Table = 1\n",
        ),
        (
            "db/gen.go",
            "//go:build ignore\n\npackage main\n\nimport \"example.com/app\"\n\nfunc main() {}\n",
        ),
    ];
    for (rel, text) in files {
        let p = root.0.join(rel);
        std::fs::create_dir_all(p.parent().unwrap_or(&root.0)).unwrap_or_default();
        std::fs::write(p, text).unwrap_or_default();
    }
    let m = scan(&root.0, &Options::new(Probe::Go)).unwrap_or_else(|e| panic!("{e}"));
    let states: Vec<(String, String)> = m
        .inventory
        .clone()
        .unwrap_or_default()
        .into_iter()
        .map(|e| (e.file, e.state))
        .collect();
    for (file, state) in [
        ("db/db_test.go", "test-only"),
        ("db/zz_gen.go", "excluded"),
        ("db/gen.go", "excluded"),
        ("main.go", "measured"),
    ] {
        assert!(
            states.contains(&(file.into(), state.into())),
            "{file}: {states:?}"
        );
    }
    let main = m
        .functions
        .iter()
        .find(|f| f.function == "main")
        .cloned()
        .unwrap_or_else(|| panic!("no main"));
    assert_eq!(
        main.coupling
            .map(|c| c.resolved_dependencies)
            .unwrap_or_default(),
        ["example.com/app/db"]
    );
    assert!(
        m.static_dependency_cycles.is_empty(),
        "the ignored generator does not fake a cycle"
    );
}
