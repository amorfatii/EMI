//! Go adapter semantics.

use std::collections::HashSet;

use emi_lang_go::coupling::{Scope, couple, package_path};
use emi_lang_go::{is_build_ignored, is_generated, measure};

#[test]
fn complexity_regions_and_declarations() {
    let src = r#"package p

const (
    A = 1
    B = 2
)

type Server struct{ n int }

func (s *Server) Handle(x int, ok bool) int {
    if x > 0 && ok || s.n == 0 {
        return 1
    }
    for i := 0; i < x; i++ {
        switch i {
        case 1, 2:
        case 3:
        default:
        }
    }
    f := func() int { if ok { return 1 }; return 0 }
    return f()
}
"#;
    let m = measure("p.go", src).unwrap_or_else(|| panic!("parse"));
    let handle = m
        .functions
        .iter()
        .find(|f| f.function == "Server.Handle")
        .unwrap_or_else(|| panic!("no method"));
    // 1 + if + && + || + for + 2 cases + closure if = 8
    assert_eq!(handle.cc, Some(8));
    let names: HashSet<&str> = m.functions.iter().map(|f| f.function.as_str()).collect();
    assert!(
        names.contains("const A") && names.contains("type Server"),
        "{names:?}"
    );
}

#[test]
fn generated_and_ignored_files_are_recognized() {
    assert!(is_generated(
        "// Code generated by stringer; DO NOT EDIT.\n\npackage p\n"
    ));
    assert!(!is_generated(
        "package p\n// Code generated by x; DO NOT EDIT.\n"
    ));
    assert!(is_build_ignored("//go:build ignore\n\npackage main\n"));
    assert!(!is_build_ignored("//go:build linux\n\npackage p\n"));
}

#[test]
fn packages_resolve_through_imports() {
    assert_eq!(
        package_path("example.com/app", "internal/db"),
        "example.com/app/internal/db"
    );
    assert_eq!(package_path("std", "net/http"), "net/http");
    let mut scope = Scope::default();
    for p in [
        "example.com/app/db",
        "example.com/app/util",
        "example.com/app/v2/api",
        "example.com/app/metrics",
    ] {
        scope.packages.insert(p.into());
    }
    scope
        .exported
        .insert("example.com/app/util".into(), ["Helper".to_owned()].into());
    let src = r#"package web

import (
    "fmt"
    store "example.com/app/db"
    . "example.com/app/util"
    "example.com/app/v2/api"
    _ "example.com/app/metrics"
)

func A() { store.Open(); fmt.Println("x") }
func B() { Helper() }
func C(c api.Client) { c.Call() }
func D(v []int) { local(len(v)) }
func local(n int) {}
"#;
    let fc = couple("example.com/app/web", src, &scope).unwrap_or_else(|| panic!("parse"));
    let m = measure("web.go", src).unwrap_or_else(|| panic!("parse"));
    let deps = |name: &str| {
        let i = m
            .functions
            .iter()
            .position(|f| f.function == name)
            .unwrap_or_else(|| panic!("{name}"));
        fc.regions[i].deps.iter().cloned().collect::<Vec<_>>()
    };
    assert_eq!(
        deps("A"),
        ["example.com/app/db"],
        "aliased import; fmt is external"
    );
    assert_eq!(
        deps("B"),
        ["example.com/app/util"],
        "dot import of an exported name"
    );
    assert_eq!(
        deps("C"),
        ["example.com/app/v2/api"],
        "qualified type through a versioned path"
    );
    assert!(deps("D").is_empty());
    let module = m
        .functions
        .iter()
        .position(|f| f.function.starts_with('<'))
        .unwrap_or(0);
    assert!(
        fc.regions[module].deps.contains("example.com/app/metrics"),
        "blank import"
    );
    let d = m
        .functions
        .iter()
        .position(|f| f.function == "D")
        .unwrap_or(0);
    assert_eq!(fc.regions[d].local_callees, ["local"]);
}
